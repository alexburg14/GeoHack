const slug = (s) =>
  s.toLowerCase().replace(/ä/g, 'ae').replace(/ö/g, 'oe').replace(/ü/g, 'ue').replace(/ß/g, 'ss').replace(/[^a-z0-9]+/g, '-');

export const STREETS = rawStreets.map((s) => ({ ...s, id: slug(s.name) }));

export const normalizeStreet = (s) =>
  s
    .toLowerCase()
    .trim()
    .replace(/ß/g, 'ss')
    .replace(/str\.?$/, 'strasse')
    .replace(/[^a-zäöü]/g, '');

export function findStreet(name) {
  const n = normalizeStreet(name);
  if (n.length < 3) return null;
  return STREETS.find((s) => normalizeStreet(s.name) === n) || STREETS.find((s) => normalizeStreet(s.name).startsWith(n)) || null;
}

export const share = (s, extra = 0) => (s.pledged + extra) / s.households;

// Anonymised view: pledges are shown per district (Ausbaugebiet), never per street.
// District shapes are generated by tools/build_districts.py from the street data.

// Colours like the official Ausbauplanung map (one pastel colour per district)
const DISTRICT_COLORS = { nord: '#8fc1e3', west: '#f0cf6e', ost: '#a9d38f', sued: '#ee9a92' };

const ringArea = (r) => r.reduce((n, [x1, y1], k) => { const [x2, y2] = r[(k + 1) % r.length]; return n + x1 * y2 - x2 * y1; }, 0) / 2;
const ringCentroid = (r) => {
  let a = 0, cx = 0, cy = 0;
  r.forEach(([x1, y1], k) => {
    const [x2, y2] = r[(k + 1) % r.length];
    const f = x1 * y2 - x2 * y1;
    a += f; cx += (x1 + x2) * f; cy += (y1 + y2) * f;
  });
  return [cy / (3 * a), cx / (3 * a)]; // [lat, lon]
};

export const AREAS = districts.features.map((f) => {
  const { id, name, streets } = f.properties;
  const members = STREETS.filter((s) => streets.includes(s.name));
  const households = members.reduce((n, s) => n + s.households, 0);
  const pledged = members.reduce((n, s) => n + s.pledged, 0);
  const phase = Math.min(...members.map((s) => s.phase));
  const byPhase = [1, 2, 3].map((p) => members.filter((s) => s.phase === p).reduce((n, s) => n + s.households, 0));
  const years = [...new Set(members.map((s) => connectionYearOf(s)))].sort();
  const mainPart = [...f.geometry.coordinates].sort((a, b) => Math.abs(ringArea(b[0])) - Math.abs(ringArea(a[0])))[0];
  return {
    id, name, streets, households, pledged, phase, byPhase, feature: f,
    color: DISTRICT_COLORS[id],
    center: ringCentroid(mainPart[0]),
    firstConnection: members.find((s) => s.phase === phase).expectedConnection,
    years: years.length > 1 ? `${years[0]}–${years[years.length - 1]}` : String(years[0]),
  };
});

function connectionYearOf(s) {
  const m = String(s.expectedConnection).match(/(19|20)\d\d/);
  return m ? Number(m[0]) : null;
}

export const areaOfStreet = (street) => (street ? AREAS.find((a) => a.streets.includes(street.name)) : null);
